// Bundles mcp-view/ (the results view shown inside Claude) into one self-contained HTML string:
// lib/mcp/view-html.generated.ts. Run after changing anything in mcp-view/: node scripts/build-mcp-view.mjs
import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const js = await build({
  entryPoints: [join(root, 'mcp-view/view.ts')],
  bundle: true, minify: true, format: 'esm', target: 'es2022', write: false, legalComments: 'none',
})
const logo = `data:image/webp;base64,${readFileSync(join(root, 'public/logo.webp')).toString('base64')}`
const css = readFileSync(join(root, 'mcp-view/view.css'), 'utf8').replace(/\s*\n\s*/g, ' ')
const script = js.outputFiles[0].text.replaceAll('__LOGO__', logo).replace(/<\/script/gi, '<\\/script')
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Build Software Solo Leads</title><style>${css}</style></head><body><div id="app"></div><script type="module">${script}</script></body></html>`
writeFileSync(
  join(root, 'lib/mcp/view-html.generated.ts'),
  `// Generated by scripts/build-mcp-view.mjs from mcp-view/. Do not edit.\nexport const VIEW_HTML = ${JSON.stringify(html)}\n`,
)
console.log(`view: ${(html.length / 1024).toFixed(1)} KB`)
